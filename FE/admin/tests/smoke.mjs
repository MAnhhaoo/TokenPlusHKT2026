import { chromium } from 'playwright'
import assert from 'node:assert/strict'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
const base = process.env.ADMIN_URL || 'http://127.0.0.1:5174'
const browser = await chromium.launch({ headless: true })
const context = await browser.newContext({viewport:{width:1440,height:1000}})
const external = [], errors = [], checks = []
await context.route('**/*', route => {
 if (route.request().url().startsWith(base+'/api/')) return route.abort()
 if (!route.request().url().startsWith(base+'/')) {external.push(route.request().url()); return route.abort()}
 return route.continue()
})
context.on('page', p => p.on('pageerror', e => errors.push(e.message)))
const page = await context.newPage()
page.setDefaultTimeout(8000)
const check = (label, value=true) => {assert.ok(value,label); checks.push(label)}
const nav = async name => {
 const menu = page.getByRole('button',{name:'Mở menu',exact:true})
 if (await menu.isVisible()) await menu.click()
 await page.getByRole('navigation').getByRole('button',{name,exact:false}).click()
}
try {
 await page.goto(base)
 await page.getByRole('heading',{level:1,name:'Tổng quan điều hành'}).waitFor()
 check('Overview has four pending reports',await page.locator('.queue-count').innerText()==='4')
 await page.getByRole('button',{name:'7 ngày',exact:true}).click()
 check('Trend range switches',await page.getByRole('button',{name:'7 ngày',exact:true}).getAttribute('aria-pressed')==='true')
 await page.locator('.report-item').first().click()
 await page.getByRole('dialog').getByRole('button',{name:'Xác nhận báo cáo'}).click()
 check('Approve updates queue',await page.locator('.queue-count').innerText()==='3')
 await page.locator('.report-item').first().click()
 await page.getByRole('dialog').getByRole('button',{name:'Từ chối',exact:true}).click()
 await page.getByLabel('Lý do từ chối').selectOption({label:'Không đủ căn cứ xác minh'})
 await page.getByRole('dialog').getByRole('button',{name:'Xác nhận từ chối'}).click()
 check('Reject updates queue',await page.locator('.queue-count').innerText()==='2')
 await nav('Bản đồ vận hành')
 check('Reject removes marker',await page.locator('.map-marker').count()===9)
 await page.getByRole('button',{name:'Nguy cơ 1',exact:false}).click()
 check('Layer filter works',await page.locator('.map-marker').count()===8)
 const transform = await page.locator('.mock-basemap > g').getAttribute('transform')
 await page.getByRole('button',{name:'Phóng to bản đồ',exact:true}).click()
 check('Map zoom changes shared transform',transform!==await page.locator('.mock-basemap > g').getAttribute('transform'))
 await page.getByRole('button',{name:'Đặt lại góc nhìn'}).click()
 check('Map reset',transform===await page.locator('.mock-basemap > g').getAttribute('transform'))
 await nav('Báo cáo cộng đồng')
 await page.locator('input[type="search"], input[placeholder*="Tìm"]').first().fill('zzzz-no-match')
 check('Reports empty filter',await page.locator('.empty-state').isVisible())
 await nav('Cảnh báo khu vực')
 await page.getByRole('button',{name:'Tạo cảnh báo',exact:true}).click()
 await page.getByLabel('Khu vực',{exact:true}).selectOption({label:'Nguyễn Văn Quá, Quận 12'})
 await page.getByLabel('Tiêu đề cảnh báo',{exact:true}).fill('Cảnh báo kiểm thử')
 await page.getByLabel('Thông điệp cho người dân',{exact:true}).fill('Nội dung mô phỏng kiểm thử')
 await page.getByRole('dialog').getByRole('button',{name:'Phát cảnh báo',exact:true}).click()
 check('Create alert',await page.locator('.alert-title').filter({hasText:'Cảnh báo kiểm thử'}).count()===1)
 const card=page.locator('.alert-card').filter({hasText:'Cảnh báo kiểm thử'})
 await card.getByRole('button',{name:'Cập nhật',exact:true}).click()
 await page.getByLabel('Tiêu đề cảnh báo',{exact:true}).fill('Cảnh báo đã sửa')
 await page.getByRole('button',{name:'Lưu thay đổi',exact:true}).click()
 check('Edit alert',await page.locator('.alert-title').filter({hasText:'Cảnh báo đã sửa'}).count()===1)
 await page.locator('.alert-card').filter({hasText:'Cảnh báo đã sửa'}).getByRole('button',{name:'Kết thúc',exact:true}).click()
 await page.getByRole('dialog').getByRole('button',{name:'Kết thúc cảnh báo',exact:true}).click()
 await page.getByRole('button',{name:/Đã kết thúc \(/}).click()
 check('End alert',await page.locator('.alert-title').filter({hasText:'Cảnh báo đã sửa'}).count()===1)
 await nav('Người dùng')
 await page.locator('.user-name-button, .user-name-btn, tbody button').first().click()
 await page.getByRole('dialog').getByRole('button',{name:'Khóa tài khoản',exact:true}).click()
 check('Block user',await page.locator('tbody').innerText().then(t=>t.includes('Đã khóa')))
 const download=page.waitForEvent('download')
 await page.getByRole('button',{name:'Xuất dữ liệu',exact:true}).click()
 check('Local CSV export',(await download).suggestedFilename().endsWith('.csv'))
 await nav('Phân tích dữ liệu')
 await page.getByRole('heading',{level:1,name:'Xu hướng mưa và báo cáo'}).waitFor()
 check('Analytics renders',await page.locator('.analytics-kpis').isVisible())
 await page.reload()
 check('Reload resets mocks',await page.locator('.queue-count').innerText()==='4')
 for(const width of [1440,390,320]) {
  await page.setViewportSize({width,height:900})
  for(const name of ['Tổng quan','Bản đồ vận hành','Báo cáo cộng đồng','Cảnh báo khu vực','Người dùng','Phân tích dữ liệu']) {
   await nav(name)
   check(`${width}px ${name}: no page overflow`,await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth))
  }
 }
 await page.setViewportSize({width:390,height:844})
 await nav('Tổng quan')
 await page.getByRole('button',{name:'Tạo cảnh báo',exact:true}).click()
 await page.keyboard.press('Tab')
 check('Modal traps keyboard focus',await page.getByRole('dialog').evaluate(el=>el.contains(document.activeElement)))
 await page.keyboard.press('Escape')
 check('Escape closes modal',await page.getByRole('dialog').count()===0)
 await page.screenshot({path:join(tmpdir(),'admin-mobile.png'),fullPage:true})
 await page.setViewportSize({width:1440,height:1000})
 await page.screenshot({path:join(tmpdir(),'admin-desktop.png'),fullPage:true})
 check('No external network requests',external.length===0)
 check('No browser exceptions',errors.length===0)
 console.log(JSON.stringify({passed:checks.length,checks,external,errors},null,2))
} finally {await browser.close()}
